const Ctx = createContext({ lang: 'en', t: (k) => k, setLang: () => {} });

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState('en');
  useEffect(() => {
    const stored = typeof window !== 'undefined' ? localStorage.getItem('sl_lang') : null;
    if (stored === 'th' || stored === 'en') setLangState(stored);
  }, []);
  const setLang = useCallback((l) => {
    setLangState(l);
    if (typeof window !== 'undefined') localStorage.setItem('sl_lang', l);
  }, []);
  const t = useCallback((key) => dict[lang]?.[key] ?? dict.en[key] ?? key, [lang]);
  return <Ctx.Provider value={{ lang, t, setLang }}>{children}</Ctx.Provider>;
}

export function useI18n() {
  return useContext(Ctx);
}
